import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { defineConfig, type Plugin } from 'vite';

const SITE = 'https://llm.aminox.dev';

/** Static pages share a header and a footer: `<!--#header-->` and `<!--#footer-->` are replaced at build time. */
function partials(): Plugin {
  const dir = resolve(__dirname, 'src/site/partials');
  return {
    name: 'partials',
    transformIndexHtml(html) {
      // The language switch links to this page's alternate, read from its own hreflang tags.
      const lang = /<html lang="(\w+)"/.exec(html)?.[1] ?? 'es';
      const other = lang === 'en' ? 'es' : 'en';
      const href = new RegExp(`<link rel="alternate" hreflang="${other}" href="${SITE.replace(/\./g, '\\.')}([^"]*)"`).exec(html)?.[1];
      return html.replace(/<!--#([\w-]+)-->/g, (_, name: string) =>
        readFileSync(join(dir, `${name}.html`), 'utf8')
          .replaceAll('{{alt-href}}', href ?? (other === 'en' ? '/en/' : '/'))
          .replaceAll('{{alt-lang}}', other)
          .replaceAll('{{alt-label}}', other === 'en' ? 'EN' : 'ES')
          .replaceAll('{{alt-title}}', other === 'en' ? 'Read in English' : 'Leer en español'),
      );
    },
  };
}

/**
 * Files in public/ keep their names, and Cloudflare tells browsers to cache them for hours, so an updated
 * icon or screenshot would not show. Every reference to one of them in the HTML gets `?v=<content hash>`.
 */
function versionPublic(): Plugin {
  const pub = resolve(__dirname, 'public');
  const cache = new Map<string, string>();
  const hash = (file: string) => {
    if (!cache.has(file)) cache.set(file, createHash('sha256').update(readFileSync(file)).digest('hex').slice(0, 10));
    return cache.get(file)!;
  };
  return {
    name: 'version-public',
    // After Vite's own HTML processing, which rewrites srcset lists.
    transformIndexHtml: {
      order: 'post',
      handler(html) {
      const version = (path: string) => {
        const file = join(pub, path);
        return existsSync(file) ? `${path}?v=${hash(file)}` : path;
      };
      return html
        .replace(/(src|href)="(\/[^"?#]+\.(?:svg|png|webp|ico|js|webmanifest|css))"/g, (_m, attr: string, path: string) => `${attr}="${version(path)}"`)
        .replace(/srcset="([^"]+)"/g, (_m, list: string) => `srcset="${list.replace(/(\/[^\s,?#]+\.(?:png|webp))/g, (p: string) => version(p))}"`);
      },
    },
  };
}

/**
 * Offline support: after the build, writes dist/sw.js, a service worker that stores the whole site (pages,
 * scripts, styles, fonts, the WebAssembly runtime) so the chat opens and works with no connection once the
 * model is downloaded. Model files are not handled here: Transformers.js keeps them in its own cache.
 */
function offline(): Plugin {
  return {
    name: 'offline-sw',
    apply: 'build',
    closeBundle() {
      const dist = resolve(__dirname, 'dist');
      const files: string[] = [];
      const walk = (dir: string) => {
        for (const f of readdirSync(dir)) {
          const p = join(dir, f);
          if (statSync(p).isDirectory()) walk(p);
          else files.push('/' + p.slice(dist.length + 1).split('\\').join('/'));
        }
      };
      walk(dist);
      // Vite rewrites srcset lists after the HTML hooks, dropping ?v=; version them in the final pages.
      const pub = resolve(__dirname, 'public');
      for (const f of files.filter((x) => x.endsWith('.html'))) {
        const file = join(dist, f);
        const html = readFileSync(file, 'utf8');
        const out = html.replace(/srcset="([^"]+)"/g, (_m, list: string) =>
          `srcset="${list.replace(/(\/[^\s,?#]+\.(?:png|webp))(?=[\s,]|$)/g, (p: string) => {
            const src = join(pub, p);
            return existsSync(src) ? `${p}?v=${createHash('sha256').update(readFileSync(src)).digest('hex').slice(0, 10)}` : p;
          })}"`,
        );
        if (out !== html) writeFileSync(file, out);
      }
      const keep = files.filter((f) => !/^\/(sw\.js|404\.html|404\.css|robots\.txt|sitemap\.xml)$/.test(f) && !/^\/assets\/ort-wasm.*\.wasm$/.test(f)); // the app loads the runtime from /ort/
      const urls = keep.map((f) => f.replace(/index\.html$/, ''));
      const version = createHash('sha256').update(keep.map((f) => f + ':' + statSync(join(dist, f)).size + ':' + createHash('sha256').update(readFileSync(join(dist, f))).digest('hex')).join('\n')).digest('hex').slice(0, 12);
      const sw = `// Generated by vite.config.ts (offline-sw). Keeps the site available without a connection.
const CACHE = 'webgpu-chat-site-${version}';
const FILES = ${JSON.stringify(urls)};
self.addEventListener('install', (e) => {
  // cache: 'reload' skips the browser's HTTP cache, which may still hold older copies of unhashed files.
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES.map((u) => new Request(u, { cache: 'reload' })))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('webgpu-chat-site-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin) return; // models come from Hugging Face: not ours
  if (req.mode === 'navigate') {
    // Pages: fresh from the network when online, from the cache when not.
    e.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          if (res.ok) caches.open(CACHE).then((c) => c.put(url.pathname, copy));
          return res;
        })
        .catch(() => caches.match(url.pathname, { ignoreSearch: true }).then((r) => r || caches.match(url.pathname + '/')).then((r) => r || caches.match('/'))),
    );
    return;
  }
  // Hashed build files (/assets/) never change: cache first. Everything else (icons, screenshots, the runtime,
  // versioned with ?v=): exact URL from the cache, else the network (and keep a copy), and only when offline
  // fall back to whatever copy of that path is stored.
  if (url.pathname.startsWith('/assets/')) {
    e.respondWith(caches.match(req).then((r) => r || fetch(req)));
    return;
  }
  e.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ||
        fetch(req)
          .then((res) => {
            if (res.ok) {
              const copy = res.clone();
              caches.open(CACHE).then((c) => c.put(req, copy));
            }
            return res;
          })
          .catch(() => caches.match(url.pathname, { ignoreSearch: true }).then((r) => r || Response.error())),
    ),
  );
});
`;
      writeFileSync(join(dist, 'sw.js'), sw);
    },
  };
}

const pages = [
  'index.html', 'app/index.html', 'aviso-legal/index.html', 'privacidad/index.html', 'terminos/index.html', 'licencias/index.html',
  'en/index.html', 'en/app/index.html', 'en/legal-notice/index.html', 'en/privacy/index.html', 'en/terms/index.html', 'en/licenses/index.html',
];

export default defineConfig({
  plugins: [partials(), versionPublic(), offline()],
  // cssTarget: modern engines, so the minifier keeps the standard backdrop-filter (Chrome ignores the -webkit- one).
  build: { target: 'es2022', cssTarget: ['chrome120', 'edge120', 'firefox121', 'safari17'], chunkSizeWarningLimit: 1200, rollupOptions: { input: pages.map((p) => resolve(__dirname, p)) } },
  worker: { format: 'es' },
  optimizeDeps: { exclude: ['@huggingface/transformers', 'onnxruntime-web'] },
});
